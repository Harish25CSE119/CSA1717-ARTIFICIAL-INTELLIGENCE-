def run_problem_2():
    print("\n" + "=" * 70)
    print(" PROBLEM 2: SMART CITY TRAFFIC SIGNAL TIMING OPTIMIZATION")
    print("=" * 70)

    num_signals = 5

    def traffic_cost(timings):
        # Objective: Minimize total delay and fuel loss
        # Mock non-linear objective with local minima
        total_delay = 0
        for i, t in enumerate(timings):
            total_delay += (t - 30) ** 2 + 10 * math.sin(t)
        return round(total_delay, 2)

    # 1. Simple Hill Climbing
    def hill_climbing():
        current = [random.randint(10, 60) for _ in range(num_signals)]
        current_cost = traffic_cost(current)

        for _ in range(100):
            neighbor = list(current)
            idx = random.randint(0, num_signals - 1)
            neighbor[idx] += random.choice([-5, 5])
            neighbor[idx] = max(10, min(60, neighbor[idx]))

            neighbor_cost = traffic_cost(neighbor)
            if neighbor_cost < current_cost:
                current = neighbor
                current_cost = neighbor_cost
            else:
                break  # Stuck at local minimum
        return current, current_cost

    # 2. Simulated Annealing
    def simulated_annealing():
        current = [random.randint(10, 60) for _ in range(num_signals)]
        current_cost = traffic_cost(current)
        T = 100.0
        alpha = 0.95

        while T > 0.1:
            neighbor = list(current)
            idx = random.randint(0, num_signals - 1)
            neighbor[idx] += random.choice([-5, 5])
            neighbor[idx] = max(10, min(60, neighbor[idx]))

            neighbor_cost = traffic_cost(neighbor)
            delta = neighbor_cost - current_cost

            if delta < 0 or random.random() < math.exp(-delta / T):
                current = neighbor
                current_cost = neighbor_cost

            T *= alpha
        return current, current_cost

    hc_sol, hc_cost = hill_climbing()
    sa_sol, sa_cost = simulated_annealing()

    print(f"-> Hill Climbing Result:      Timings={hc_sol} | Congestion Cost={hc_cost}")
    print(f"-> Simulated Annealing Result: Timings={sa_sol} | Congestion Cost={sa_cost}")
    print("\n[Recommendation]: GA/Memetic Parallel Search to optimize multi-objective traffic corridors.")


