# PROBLEM 4: Automated University Exam Timetabling (CSP)
# Algorithms: Backtracking with Forward Checking & MRV Heuristic
# =====================================================================
def run_problem_4():
    print("\n" + "=" * 70)
    print(" PROBLEM 4: AUTOMATED EXAM TIMETABLING (CSP)")
    print("=" * 70)

    exams = ["CS101", "CS102", "MA101", "PH101"]
    time_slots = ["Mon_AM", "Mon_PM", "Tue_AM"]

    # Hard Constraints: Overlapping students cannot take exams at the same time
    conflicts = {
        "CS101": ["CS102", "MA101"],
        "CS102": ["CS101", "PH101"],
        "MA101": ["CS101", "PH101"],
        "PH101": ["CS102", "MA101"],
    }

    assignment = {}

    def is_consistent(exam, slot):
        for neighbor in conflicts[exam]:
            if neighbor in assignment and assignment[neighbor] == slot:
                return False
        return True

    def backtrack_csp():
        if len(assignment) == len(exams):
            return True

        # MRV Heuristic: Pick unassigned exam with fewest legal choices
        unassigned = [e for e in exams if e not in assignment]
        unassigned.sort(
            key=lambda e: sum(1 for s in time_slots if is_consistent(e, s))
        )
        exam = unassigned[0]

        for slot in time_slots:
            if is_consistent(exam, slot):
                assignment[exam] = slot
                if backtrack_csp():
                    return True
                del assignment[exam]
        return False

    if backtrack_csp():
        print("-> Valid Timetable Schedule Generated Successfully (No Overlaps):")
        for exam, slot in assignment.items():
            print(f"   * {exam} --> {slot}")
    else:
        print("-> No valid timetable configuration found under given constraints.")

    print("\n[Recommendation]: Hybrid Backtracking (AC-3 + MRV) combined with Genetic Local Search.")


