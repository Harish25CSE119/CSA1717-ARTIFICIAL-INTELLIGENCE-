def run_problem_5():
    print("\n" + "=" * 70)
    print(" PROBLEM 5: REAL-TIME STRATEGY GAME AI (ALPHA-BETA PRUNING)")
    print("=" * 70)

    # Simulated Game Tree Terminal Leaf Evaluation Scores
    leaf_nodes = [3, 5, 6, 9, 1, 2, 0, -1]
    print(f"Evaluation Scores at Game Tree Depth 3: {leaf_nodes}")

    pruned_branches = 0

    def alpha_beta(depth, node_index, is_max, alpha, beta):
        nonlocal pruned_branches

        if depth == 3:
            return leaf_nodes[node_index]

        if is_max:
            max_eval = -math.inf
            for i in range(2):
                val = alpha_beta(
                    depth + 1, node_index * 2 + i, False, alpha, beta
                )
                max_eval = max(max_eval, val)
                alpha = max(alpha, val)
                if beta <= alpha:
                    pruned_branches += 1
                    break  # Beta Cutoff
            return max_eval
        else:
            min_eval = math.inf
            for i in range(2):
                val = alpha_beta(
                    depth + 1, node_index * 2 + i, True, alpha, beta
                )
                min_eval = min(min_eval, val)
                beta = min(beta, val)
                if beta <= alpha:
                    pruned_branches += 1
                    break  # Alpha Cutoff
            return min_eval

    optimal_val = alpha_beta(0, 0, True, -math.inf, math.inf)

    print(f"-> Minimax Optimal Value for AI: {optimal_val}")
    print(f"-> Number of Pruned Subtrees:    {pruned_branches}")
    print("\n[Recommendation]: Iterative Deepening Minimax + Transposition Tables for Real-Time Budgets.")


