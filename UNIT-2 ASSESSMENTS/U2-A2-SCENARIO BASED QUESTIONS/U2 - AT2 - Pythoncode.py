# PROBLEM 3: Autonomous Mars Rover Navigation
# Algorithm: Online Search (Learning Real-Time A* - LRTA* Simulation)
# =====================================================================
def run_problem_3():
    print("\n" + "=" * 70)
    print(" PROBLEM 3: AUTONOMOUS MARS ROVER ONLINE NAVIGATION (LRTA*)")
    print("=" * 70)

    # Environment unknown ahead of time
    grid_size = 5
    goal = (4, 4)

    # Heuristic table H initialized to straight line distances
    H = {
        (x, y): math.sqrt((4 - x) ** 2 + (4 - y) ** 2)
        for x in range(grid_size)
        for y in range(grid_size)
    }

    # Obstacles detected dynamically on arrival
    dynamic_obstacles = {(1, 1), (1, 2), (2, 2), (3, 1)}

    current = (0, 0)
    path = [current]

    print(f"Starting LRTA* Rover Execution from {current} to {goal}...")

    steps = 0
    while current != goal and steps < 20:
        steps += 1
        # Look at valid neighbors
        neighbors = []
        for dx, dy in [(-1, 0), (1, 0), (0, -1), (0, 1)]:
            nx, ny = current[0] + dx, current[1] + dy
            if (
                0 <= nx < grid_size
                and 0 <= ny < grid_size
                and (nx, ny) not in dynamic_obstacles
            ):
                neighbors.append((nx, ny))

        if not neighbors:
            print("-> Rover Trapped!")
            break

        # Select neighbor with min (cost + H(s'))
        best_neighbor = min(neighbors, key=lambda s: 1 + H[s])

        # Update heuristic of current state
        H[current] = 1 + H[best_neighbor]

        # Execute step online
        current = best_neighbor
        path.append(current)

    print(f"-> Online Exploration Path Executed: {path}")
    print("\n[Recommendation]: LRTA* + EKF-SLAM for real-time dynamic obstacle avoidance on Mars.")


